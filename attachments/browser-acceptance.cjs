const {chromium}=require('playwright');
const {readFileSync,writeFileSync}=require('node:fs');
const {execFileSync}=require('node:child_process');
const assert=require('node:assert/strict');
const meta=JSON.parse(readFileSync(__dirname+'/meta.json'));
(async()=>{
 const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1200}});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 try{
  await page.goto('http://127.0.0.1:'+meta.port+'/game?game='+encodeURIComponent(meta.game));
  await page.locator('#join-game').click();
  await page.locator('#action-confirmation').waitFor({state:'visible'});
  assert.match(await page.locator('#action-key-warning').innerText(),/unanchored/i);
  const key=await page.locator('#identity-fingerprint').innerText();
  await page.screenshot({path:__dirname+'/join-confirmation.png',fullPage:true});
  await page.locator('#sign-game-action').click();
  await page.waitForFunction(()=>document.querySelector('.game-status').textContent.includes('w to move') || document.querySelector('.game-status').textContent.includes('white to move'));
  execFileSync(meta.binary,['move','--repo',meta.repo,'--game',meta.game,'--move','e2e4']);
  await page.waitForFunction(()=>document.querySelector('#last-move').textContent.includes('e2e4'),{},{timeout:30000});
  assert.equal(await page.locator('#identity-fingerprint').innerText(),key);
  await page.locator('[data-square="e7"]').click();
  await page.locator('[data-square="e5"].legal').waitFor();
  await page.locator('[data-square="e5"]').click();
  await page.locator('#action-confirmation').waitFor({state:'visible'});
  assert.match(await page.locator('#action-description').innerText(),/e7e5/);
  await page.screenshot({path:__dirname+'/move-confirmation.png',fullPage:true});
  let firstSubmission, firstResult;
  await page.route('**/v1/actions/submit', async route => {
   firstSubmission=route.request().postData();
   const response=await route.fetch(); firstResult=await response.json();
   await route.abort('failed');
   await page.unroute('**/v1/actions/submit');
  });
  await page.locator('#sign-game-action').click();
  await page.getByRole('button',{name:'Retry the same signed action',exact:true}).waitFor();
  const responsePromise=page.waitForResponse(r=>r.url().endsWith('/v1/actions/submit'));
  await page.getByRole('button',{name:'Retry the same signed action',exact:true}).click();
  const retryResponse=await responsePromise, retried=await retryResponse.json();
  assert.equal(retryResponse.request().postData(),firstSubmission);
  assert.equal(retried.record,firstResult.record);assert.equal(retried.depth,firstResult.depth);
  await page.waitForFunction(()=>document.querySelector('#last-move').textContent.includes('e7e5'));
  assert.equal(await page.locator('#identity-fingerprint').innerText(),key);
  await page.screenshot({path:__dirname+'/move-accepted.png',fullPage:true});
  await page.reload();
  assert.equal(await page.locator('#identity-fingerprint').innerText(),'No tab key yet');
  await page.locator('#create-tab-key').click();
  await page.waitForFunction(()=>/^[a-f0-9]{64}$/.test(document.querySelector('#identity-fingerprint').textContent));
  const replacement=await page.locator('#identity-fingerprint').innerText();assert.notEqual(replacement,key);
  execFileSync(meta.binary,['move','--repo',meta.repo,'--game',meta.game,'--move','g1f3']);
  await page.waitForFunction(()=>document.querySelector('#last-move').textContent.includes('g1f3'),{},{timeout:30000});
  await page.locator('[data-square="b8"]').click();
  await page.locator('[data-square="c6"].legal').waitFor();
  await page.locator('[data-square="c6"]').click();
  await page.locator('#action-confirmation').waitFor({state:'visible'});
  await page.locator('#sign-game-action').click();
  await page.locator('.game-refusals').waitFor({state:'visible'});
  assert.match(await page.locator('#last-move').innerText(),/g1f3/);
  assert.deepEqual(errors,[]);
  const summary={game:meta.game,tabKey:key,replacementKey:replacement,joined:true,cliMoveRefreshedWithoutReload:true,browserMoveAccepted:true,lostResponseRetrySameBytesAndRecord:true,retryDepth:firstResult.depth,reloadLostKey:true,replacementRefused:await page.locator('.game-refusals').innerText(),pageErrors:errors};
  writeFileSync(__dirname+'/browser-summary.json',JSON.stringify(summary,null,2));console.log(JSON.stringify(summary));
 }catch(e){await page.screenshot({path:__dirname+'/failure.png',fullPage:true});console.error(await page.locator('body').innerText());throw e;}
 finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
